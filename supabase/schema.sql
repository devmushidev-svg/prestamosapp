begin
  if exists (
    select 1
    from pago_aplicaciones a
    join cuotas c on c.id = a.cuota_id
    group by c.id, c.monto
    having sum(a.monto) > c.monto
  ) then
    raise exception 'Hay pagos históricos que exceden el monto de su cuota';
  end if;
end $$;

