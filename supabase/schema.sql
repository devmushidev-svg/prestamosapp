declare
  v_prestamos text;
begin
  select string_agg(p.id::text, ', ' order by p.id::text)
  into v_prestamos
  from public.prestamos p
  where p.estado <> 'cancelado'
    and p.saldo is distinct from (
    select coalesce(sum(c.monto - c.monto_pagado), 0)
    from public.cuotas c
    where c.prestamo_id = p.id
  );

  if v_prestamos is not null then
    raise exception 'El saldo no coincide con las cuotas en préstamo(s): %', v_prestamos;
  end if;
end $$;

