  prefijo_recibo text not null default 'REC',
  digitos_recibo smallint not null default 6,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists prestamos (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  cliente_id uuid not null,
  monto numeric(14,2) not null check (monto > 0),
  tasa_interes numeric(6,2) not null default 0
    constraint prestamos_tasa_no_negativa check (tasa_interes >= 0),
  plazo integer not null check (plazo > 0),
  frecuencia text not null
    constraint prestamos_frecuencia_valida
    check (frecuencia in ('diario', 'semanal', 'quincenal', 'mensual')),
  fecha_inicio date not null default ((clock_timestamp() at time zone 'America/Tegucigalpa')::date),
  fecha_primer_pago date,
  dia_pago_semana smallint,
  tasa_mora numeric(5,2) not null default 1.50
    constraint prestamos_tasa_mora_no_negativa check (tasa_mora >= 0),
  saldo numeric(14,2) not null
    constraint prestamos_saldo_no_negativo check (saldo >= 0),
  estado text not null default 'activo'
    check (estado in ('activo', 'al_dia', 'en_mora', 'pagado', 'cancelado')),
  solicitud_id uuid,
  creado_en timestamptz not null default now()
);

create table if not exists cuotas (
  id uuid primary key default gen_random_uuid(),
  prestamo_id uuid not null references prestamos(id) on delete cascade,
  numero integer not null
    constraint cuotas_numero_positivo check (numero > 0),
  fecha_vencimiento date not null,
  monto numeric(14,2) not null
    constraint cuotas_monto_positivo check (monto > 0),
  monto_pagado numeric(14,2) not null default 0,
  estado text not null default 'pendiente'
    check (estado in ('pendiente', 'pagada', 'vencida')),
  unique (prestamo_id, numero),
  constraint cuotas_id_prestamo_unique unique (id, prestamo_id)
);

create table if not exists pagos (
  id uuid primary key default gen_random_uuid(),
  prestamo_id uuid not null references prestamos(id),
  cuota_id uuid,
  solicitud_id uuid not null default gen_random_uuid(),
  numero_recibo bigint generated by default as identity unique,
  fecha timestamptz not null default now(),
  monto numeric(14,2) not null check (monto > 0),
  recibo text,
  saldo_anterior numeric(14,2),
  saldo_posterior numeric(14,2),
  notas text,
  datos_recibo jsonb,
  creado_en timestamptz not null default now(),
  constraint pagos_id_prestamo_unique unique (id, prestamo_id),
  constraint pagos_cuota_prestamo_fk
    foreign key (cuota_id, prestamo_id) references cuotas(id, prestamo_id)
