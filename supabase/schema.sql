-- Un solo prestamista/negocio durante el MVP. No se crea una fila por defecto:
-- su ausencia activa la configuración inicial después del primer login.
create table if not exists configuracion_prestamista (
  id smallint primary key default 1 check (id = 1),
  nombre_negocio text not null check (btrim(nombre_negocio) <> ''),
  nombre_propietario text not null check (btrim(nombre_propietario) <> ''),
  rtn text,
