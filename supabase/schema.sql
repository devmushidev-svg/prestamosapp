-- Crea el préstamo y todas sus cuotas dentro de una sola transacción.
-- Interés fijo total: capital + round(capital * tasa / 100, 2).
-- El calendario coincide con `loanCalculator.ts`: diario cada día calendario,
-- semanal en el próximo día fijo, quincenal cada 15 días y mensual por mes.
-- Los centavos sobrantes se reparten para que la suma coincida con el saldo.
drop function if exists public.crear_prestamo_con_cuotas(uuid, numeric, numeric, integer, text, date);

create or replace function public.crear_prestamo_con_cuotas(
  p_solicitud_id uuid,
  p_cliente_id uuid,
  p_monto numeric,
  p_tasa_interes numeric,
  p_plazo integer,
  p_frecuencia text,
  p_fecha_inicio date,
  p_dia_pago_semana smallint
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_prestamo_id uuid;
  v_existing public.prestamos%rowtype;
  v_interes numeric;
  v_total numeric;
  v_total_centavos bigint;
  v_base_centavos bigint;
  v_sobrante bigint;
  v_fecha_primer_pago date;
  v_dia_inicio integer;
  v_delta_dias integer;
begin
  if p_solicitud_id is null then
    raise exception using message = 'La identificación de solicitud es obligatoria', errcode = '23502';
  end if;
  if p_cliente_id is null then
    raise exception using message = 'El cliente es obligatorio', errcode = '23502';
  end if;
  if p_monto is null or p_monto <= 0 or p_monto > 999999999999.99
    or p_monto <> round(p_monto, 2) then
    raise exception using message = 'El capital debe ser positivo y tener máximo dos decimales', errcode = '23514';
  end if;
  if p_tasa_interes is null or p_tasa_interes < 0 or p_tasa_interes > 9999.99
    or p_tasa_interes <> round(p_tasa_interes, 2) then
    raise exception using message = 'La tasa debe estar entre 0 y 9999.99 y tener máximo dos decimales', errcode = '23514';
  end if;
  if p_plazo is null or p_plazo < 1 or p_plazo > 600 then
    raise exception using message = 'El plazo debe estar entre 1 y 600 cuotas', errcode = '23514';
  end if;
  if p_frecuencia is null or p_frecuencia not in ('diario', 'semanal', 'quincenal', 'mensual') then
    raise exception using message = 'La frecuencia no es válida', errcode = '23514';
  end if;
  if p_fecha_inicio is null then
    raise exception using message = 'La fecha de inicio es obligatoria', errcode = '23502';
  end if;
  if p_frecuencia = 'diario' then
    if not (
      (p_plazo = 24 and p_tasa_interes in (15, 20))
      or (p_plazo = 40 and p_tasa_interes in (30, 40))
    ) then
      raise exception using message = 'El plan diario no coincide con un plazo y una tasa permitidos', errcode = '23514';
    end if;
  elsif p_frecuencia = 'semanal' and p_plazo not in (12, 24, 36, 48) then
    raise exception using message = 'El plan semanal solo permite 3, 6, 9 o 12 meses', errcode = '23514';
  elsif p_frecuencia = 'quincenal' and p_plazo not in (18, 24) then
    raise exception using message = 'El plan quincenal solo permite 9 o 12 meses', errcode = '23514';
  end if;

  if p_frecuencia = 'semanal' then
    if p_dia_pago_semana is null or p_dia_pago_semana not between 1 and 6 then
      raise exception using message = 'El día de cobro semanal debe estar entre lunes y sábado', errcode = '23514';
    end if;
  elsif p_dia_pago_semana is not null then
    raise exception using message = 'El día de cobro semanal solo aplica a préstamos semanales', errcode = '23514';
  end if;

  perform 1 from public.clientes where id = p_cliente_id;
  if not found then
    raise exception using message = 'El cliente no existe', errcode = '23503';
  end if;

  v_interes := round(p_monto * p_tasa_interes / 100, 2);
  v_total := p_monto + v_interes;
  if v_total > 999999999999.99 then
    raise exception using message = 'El total del préstamo excede el máximo permitido', errcode = '22003';
  end if;

  v_total_centavos := round(v_total * 100)::bigint;
  v_base_centavos := v_total_centavos / p_plazo;
  v_sobrante := mod(v_total_centavos, p_plazo::bigint);
  if v_base_centavos < 1 then
    raise exception using message = 'El total es demasiado bajo para la cantidad de cuotas', errcode = '23514';
  end if;

  if p_frecuencia = 'semanal' then
    v_dia_inicio := extract(isodow from p_fecha_inicio)::integer;
    v_delta_dias := mod(p_dia_pago_semana::integer - v_dia_inicio + 7, 7);
    if v_delta_dias = 0 then
      v_delta_dias := 7;
    end if;
    v_fecha_primer_pago := p_fecha_inicio + v_delta_dias;
  else
    v_fecha_primer_pago := case p_frecuencia
      when 'diario' then p_fecha_inicio + 1
      when 'quincenal' then p_fecha_inicio + 15
      else (p_fecha_inicio + make_interval(months => 1))::date
    end;
  end if;

  insert into public.prestamos (
    solicitud_id, cliente_id, monto, tasa_interes, plazo, frecuencia,
    fecha_inicio, fecha_primer_pago, dia_pago_semana, tasa_mora, saldo, estado
  ) values (
    p_solicitud_id, p_cliente_id, p_monto, p_tasa_interes, p_plazo, p_frecuencia,
    p_fecha_inicio, v_fecha_primer_pago, p_dia_pago_semana, 1.50, v_total, 'activo'
  )
  on conflict (solicitud_id) do nothing
  returning id into v_prestamo_id;

  if v_prestamo_id is null then
    select * into v_existing
    from public.prestamos
    where solicitud_id = p_solicitud_id;

    if not found then
      raise exception using message = 'No se pudo confirmar la solicitud del préstamo', errcode = '40001';
    end if;
    if v_existing.cliente_id is distinct from p_cliente_id
      or v_existing.monto is distinct from p_monto
      or v_existing.tasa_interes is distinct from p_tasa_interes
      or v_existing.plazo is distinct from p_plazo
      or v_existing.frecuencia is distinct from p_frecuencia
      or v_existing.fecha_inicio is distinct from p_fecha_inicio
      or v_existing.dia_pago_semana is distinct from p_dia_pago_semana then
      raise exception using message = 'La solicitud ya fue usada con datos diferentes', errcode = '23505';
    end if;
    return v_existing.id;
  end if;

  insert into public.cuotas (prestamo_id, numero, fecha_vencimiento, monto, estado)
  select
    v_prestamo_id,
    serie.numero,
    case p_frecuencia
      when 'diario' then p_fecha_inicio + serie.numero
      when 'semanal' then v_fecha_primer_pago + ((serie.numero - 1) * 7)
      when 'quincenal' then p_fecha_inicio + (serie.numero * 15)
      else (p_fecha_inicio + make_interval(months => serie.numero))::date
    end,
    (
      v_base_centavos + case when serie.numero <= v_sobrante then 1 else 0 end
    )::numeric / 100,
    'pendiente'
  from generate_series(1, p_plazo) as serie(numero);

  return v_prestamo_id;
end;
$$;

